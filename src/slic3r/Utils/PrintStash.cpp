json PrintStash::extract_native_context(const fs::path &gcode)
{
    static const std::regex::flag_type fl = std::regex::ECMAScript | std::regex::icase;
    static const std::regex marker_re(R"(^;\s*printstash:([a-z_]+)\s*=\s*(.*?)\s*$)", fl);
    static const std::regex label_re(R"(^;\s*printing object\s+(.+?)\s+id:(\S+)\s+copy\s+(\d+)\s*$)", fl);
    static const std::regex generated_re(R"(^;\s*generated by\s+(\S+)\s+([^\s]+))", fl);
    static const std::regex time_re(R"(^;\s*TIME\s*:\s*(\d+(?:\.\d+)?)\s*$)", fl);
    static const std::regex weight_re(R"(^;\s*(?:total )?filament used \[g\]\s*=\s*([\d.]+))", fl);
    static const std::regex length_re(R"(^;\s*(?:total )?filament (?:used|length) \[mm\]\s*=\s*([\d.]+))", fl);
    static const std::regex cost_re(R"(^;\s*(?:total )?filament cost\s*=\s*([\d.]+))", fl);

    std::map<std::string, std::string> markers, config;
    struct Label { std::string name, object_id; int copy; };
    std::vector<Label>                                        labels;
    std::set<std::tuple<std::string, std::string, int>>       label_keys;
    json                                                      stats = json::object();
    std::optional<std::string>                                slicer_version;

    static const std::map<std::string, std::string> aliases = {
        {"input_filename", "source_filename"}, {"num_objects", "object_count"}, {"num_instances", "instance_count"}};

    boost::nowide::ifstream in(gcode.string(), std::ios::binary);
    std::string             line;
    std::smatch             m;
    while (std::getline(in, line)) {
        if (line.empty() || line[0] != ';') continue; // cheap reject of all motion lines
        if (!line.empty() && line.back() == '\r') line.pop_back();

        const bool has_eq = line.find('=') != std::string::npos;
        const bool is_marker = has_eq && boost::icontains(line, "printstash:");
        if (is_marker && std::regex_match(line, m, marker_re)) {
            std::string key = boost::to_lower_copy(m[1].str());
            auto        it  = aliases.find(key);
            if (it != aliases.end()) key = it->second;
            if (auto v = clean(m[2].str())) markers[key] = *v;
            continue;
        }
        if (boost::icontains(line, "printing object") && std::regex_match(line, m, label_re)) {
            auto key = std::make_tuple(m[1].str(), m[2].str(), std::stoi(m[3].str()));
            if (label_keys.insert(key).second) labels.push_back({std::get<0>(key), std::get<1>(key), std::get<2>(key)});
            continue;
        }
        if (!slicer_version && boost::icontains(line, "generated by") && std::regex_search(line, m, generated_re))
            slicer_version = m[2].str();
        if (!has_eq && boost::icontains(line, "TIME") && std::regex_match(line, m, time_re)) {
            if (!stats.contains("estimated_time_s")) stats["estimated_time_s"] = static_cast<long long>(std::stod(m[1].str()));
        }
        if (has_eq) {
            // std::regex recurses per character: keep it away from very long lines (custom G-code in the config block).
            if (line.size() <= 512) {
                if (std::regex_search(line, m, weight_re)) stats["filament_weight_g"] = std::stod(m[1].str());
                if (std::regex_search(line, m, length_re)) stats["filament_length_mm"] = std::stod(m[1].str());
                if (std::regex_search(line, m, cost_re)) stats["filament_cost"] = std::stod(m[1].str());
            }
            // "; key = value" config line, parsed by hand (values can be arbitrarily long).
            size_t i = 1;
            while (i < line.size() && std::isspace(static_cast<unsigned char>(line[i]))) ++i;
            const size_t key_begin = i;
            while (i < line.size() && (std::isalnum(static_cast<unsigned char>(line[i])) || line[i] == '_')) ++i;
            const size_t key_end = i;
            while (i < line.size() && std::isspace(static_cast<unsigned char>(line[i]))) ++i;
            if (key_end > key_begin && i < line.size() && line[i] == '=')
                config[boost::to_lower_copy(line.substr(key_begin, key_end - key_begin))] = boost::trim_copy(line.substr(i + 1));
        }
    }

    auto get = [](const std::map<std::string, std::string> &mp, const char *k) -> std::string {
        auto it = mp.find(k);
        return it == mp.end() ? std::string() : it->second;
    };

    std::set<std::string> object_ids;
    for (auto &l : labels) object_ids.insert(l.object_id);
    const std::optional<int> label_object_count   = object_ids.empty() ? std::nullopt : std::optional<int>(int(object_ids.size()));
    const std::optional<int> label_instance_count = labels.empty() ? std::nullopt : std::optional<int>(int(labels.size()));

    std::optional<std::string> label_filename;
    if (label_object_count == 1 && !labels.empty()) label_filename = source_filename(labels.front().name);
    const auto marker_filename = source_filename(get(markers, "source_filename"));
    const auto src_filename    = marker_filename ? marker_filename : label_filename;

    auto max_count = [](std::optional<int> a, std::optional<int> b) -> std::optional<int> {
        if (a && b) return std::max(*a, *b);
        return a ? a : b;
    };
    const auto marker_object_count   = as_count(get(markers, "object_count"));
    const auto marker_instance_count = as_count(get(markers, "instance_count"));
    const auto object_count   = max_count(marker_object_count, label_object_count);
    const auto instance_count = max_count(marker_instance_count, label_instance_count);

    std::string classification = "unknown";
    if (object_count == 1 && src_filename) classification = "single_object";
    else if (object_count && *object_count > 1) classification = "multi_object";

    json field_sources = json::object();
    if (src_filename) field_sources["source.filename"] = marker_filename ? "gcode_marker" : "gcode_object_label";
    if (!labels.empty()) field_sources["source.object_labels"] = "gcode_object_label";
    if (object_count) field_sources["source.object_count"] = (marker_object_count == object_count) ? "gcode_marker" : "gcode_object_label";
    if (instance_count) field_sources["source.instance_count"] = (marker_instance_count == instance_count) ? "gcode_marker" : "gcode_object_label";

    const auto marker_first_object = clean(get(markers, "first_object_name"));
    std::optional<std::string> first_object = marker_first_object ? marker_first_object : label_filename;
    if (first_object) field_sources["source.first_object_name"] = marker_first_object ? "gcode_marker" : "gcode_object_label";
    const auto plate_name = clean(get(markers, "plate_name"));
    if (plate_name) field_sources["source.plate_name"] = "gcode_marker";
    const auto project_name = clean(get(markers, "project_name"));
    if (project_name) field_sources["source.project_name"] = "gcode_marker";

    const auto printer_model  = clean(get(config, "printer_model"));
    const auto printer_preset = clean(get(config, "printer_settings_id"));
    const auto process_preset = clean(get(config, "print_settings_id"));
    if (printer_model) field_sources["printer.model"] = "gcode_comments";
    if (printer_preset) field_sources["printer.preset"] = "gcode_comments";
    if (process_preset) field_sources["process.preset"] = "gcode_comments";

    const auto types   = split_list(get(config, "filament_type"));
    const auto presets = split_list(get(config, "filament_settings_id"));
    json       filaments = json::array();
    for (size_t i = 0; i < std::max(types.size(), presets.size()); ++i)
        filaments.push_back({{"type", i < types.size() ? json(types[i]) : json(nullptr)},
                             {"preset", i < presets.size() ? json(presets[i]) : json(nullptr)}});
    if (!filaments.empty()) field_sources["filaments"] = "gcode_comments";
    if (slicer_version) {
        field_sources["slicer.name"]    = "gcode_header";
        field_sources["slicer.version"] = "gcode_header";
    }
    for (auto it = stats.begin(); it != stats.end(); ++it)
        field_sources["print_stats." + it.key()] = it.key() == "estimated_time_s" ? "gcode_header" : "gcode_comments";

    json object_labels = json::array();
    for (auto &l : labels) object_labels.push_back({{"name", l.name}, {"object_id", l.object_id}, {"copy_index", l.copy}});

    json basename = nullptr;
    if (src_filename) basename = fs::path(*src_filename).stem().string();

    json ctx;
    ctx["version"]        = 1;
    ctx["classification"] = classification;
    ctx["source"] = {{"filename", opt_json(src_filename)},
                     {"basename", basename},
                     {"first_object_name", opt_json(first_object)},
                     {"object_count", object_count ? json(*object_count) : json(nullptr)},
                     {"instance_count", instance_count ? json(*instance_count) : json(nullptr)},
                     {"plate_name", opt_json(plate_name)},
                     {"project_name", opt_json(project_name)},
                     {"object_labels", object_labels}};
    ctx["slicer"]        = {{"name", slicer_version ? json("OrcaSlicer") : json(nullptr)}, {"version", opt_json(slicer_version)}};
    ctx["printer"]       = {{"model", opt_json(printer_model)}, {"preset", opt_json(printer_preset)}};
    ctx["filaments"]     = filaments;
    ctx["process"]       = {{"preset", opt_json(process_preset)}};
    ctx["print_stats"]   = stats;
    ctx["field_sources"] = field_sources;
    return ctx;
}

