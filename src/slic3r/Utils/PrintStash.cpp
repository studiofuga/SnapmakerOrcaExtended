// Idempotency key: sha256(file bytes || compact context JSON), same recipe as the Python hook.
std::string submission_id(const fs::path &file, const json &context)
{
    std::unique_ptr<EVP_MD_CTX, decltype(&EVP_MD_CTX_free)> ctx(EVP_MD_CTX_new(), EVP_MD_CTX_free);
    EVP_DigestInit_ex(ctx.get(), EVP_sha256(), nullptr);
    boost::nowide::ifstream in(file.string(), std::ios::binary);
    std::vector<char>       buf(1 << 20);
    while (in) {
        in.read(buf.data(), buf.size());
        if (in.gcount() > 0) EVP_DigestUpdate(ctx.get(), buf.data(), size_t(in.gcount()));
    }
    const std::string c = context.dump(-1, ' ', true);
    EVP_DigestUpdate(ctx.get(), c.data(), c.size());
    unsigned char md[EVP_MAX_MD_SIZE];
    unsigned int  len = 0;
    EVP_DigestFinal_ex(ctx.get(), md, &len);
    static const char *hex = "0123456789abcdef";
    std::string        out;
    for (unsigned i = 0; i < len; ++i) { out += hex[md[i] >> 4]; out += hex[md[i] & 15]; }
    return out;
}

