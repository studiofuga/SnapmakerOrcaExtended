std::optional<std::string> clean(const std::string &value)
{
    std::string s = boost::trim_copy(value);
    boost::trim_if(s, [](char c) { return c == '"'; });
    boost::trim(s);
    if (s.empty() || (s.front() == '{' && s.back() == '}')) return std::nullopt;
    return s;
}

std::vector<std::string> split_list(const std::string &value)
{
    std::vector<std::string> out;
    auto c = clean(value);
    if (!c) return out;
    std::vector<std::string> parts;
    boost::split(parts, *c, boost::is_any_of(";,"));
    for (auto &p : parts) {
        boost::trim(p);
        boost::trim_if(p, [](char ch) { return ch == '"'; });
        if (!p.empty()) out.push_back(p);
    }
    return out;
}

std::optional<int> as_count(const std::string &value)
{
    auto c = clean(value);
    if (!c) return std::nullopt;
    try {
        size_t pos = 0;
        int    n   = std::stoi(*c, &pos);
        if (pos != c->size() || n < 0 || n > 100000) return std::nullopt;
        return n;
    } catch (...) { return std::nullopt; }
}

std::optional<std::string> source_filename(const std::string &value)
{
    auto c = clean(value);
    if (!c) return std::nullopt;
    std::string s = *c;
    std::replace(s.begin(), s.end(), '\\', '/');
    const auto slash = s.find_last_of('/');
    if (slash != std::string::npos) s = s.substr(slash + 1);
    static const char *suffixes[] = {".stl", ".3mf", ".obj", ".step", ".stp", ".dxf"};
    for (const char *suf : suffixes)
        if (boost::iends_with(s, suf)) return s;
    return std::nullopt;
}

json opt_json(const std::optional<std::string> &v) { return v ? json(*v) : json(nullptr); }

