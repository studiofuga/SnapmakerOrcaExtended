PrintStashSettings PrintStashSettings::load(const AppConfig &c)
{
    PrintStashSettings s;
    s.host       = c.get("printstash_host");
    s.port       = c.get("printstash_port");
    s.use_https  = c.get("printstash_https") == "true";
    s.username   = c.get("printstash_username");
    s.api_key    = c.get("printstash_api_key");
    s.collection = c.get("printstash_collection");
    s.tags       = c.get("printstash_tags");
    return s;
}

void PrintStashSettings::save(AppConfig &c) const
{
    c.set("printstash_host", host);
    c.set("printstash_port", port);
    c.set("printstash_https", use_https ? "true" : "false");
    c.set("printstash_username", username);
    c.set("printstash_api_key", api_key);
    c.set("printstash_collection", collection);
    c.set("printstash_tags", tags);
}

bool PrintStashSettings::valid() const { return !boost::trim_copy(host).empty() && !username.empty() && !api_key.empty(); }

std::string PrintStashSettings::base_url() const
{
    std::string h = boost::trim_copy(host);
    std::string scheme = use_https ? "https" : "http";
    if (boost::istarts_with(h, "https://")) { scheme = "https"; h = h.substr(8); }
    else if (boost::istarts_with(h, "http://")) { scheme = "http"; h = h.substr(7); }
    while (!h.empty() && h.back() == '/') h.pop_back();
    std::string url = scheme + "://" + h;
    const std::string p = boost::trim_copy(port);
    // Do not append the port if the user already typed one in the host field.
    if (!p.empty() && h.find(':') == std::string::npos) url += ":" + p;
    return url;
}

